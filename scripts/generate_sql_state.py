#!/usr/bin/env python3
"""Write src/dream_postgres/sql_state.gleam from PostgreSQL's errcodes.txt.

The input is every file in test/fixtures/errcodes: errcodes.txt of each
supported PostgreSQL version, copied from src/backend/utils/errcodes.txt of
the server source. The output has one variant for each SQLSTATE code that
any of those versions has.

The variant's name is the code's condition name (its PL/pgSQL name) in
PascalCase. Five condition names belong to two codes each. For those, both
codes take their class's condition name as a prefix, for example
`WarningStringDataRightTruncation` (01004) and
`DataExceptionStringDataRightTruncation` (22001).

Run it from the repository root:

    python3 scripts/generate_sql_state.py

The test sql_state_test checks the output against the same files, so a
change to a file without a new run of this script fails the tests.
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
INPUT_DIRECTORY = ROOT / "test" / "fixtures" / "errcodes"
OUTPUT_FILE = ROOT / "src" / "dream_postgres" / "sql_state.gleam"
CLASS_LINE = re.compile(r"^Section: Class ([0-9A-Z]{2}) - ([^(]+?)\s*(?:\(.*)?$")
CODE_LINE = re.compile(r"^([0-9A-Z]{5})\s+([EWS])\s+(ERRCODE_[A-Z0-9_]+)(?:\s+([a-z0-9_]+))?\s*$")


def read_codes():
    """Every named code of every input file: code -> (severity, name, versions)."""
    codes = {}
    for path in sorted(INPUT_DIRECTORY.glob("postgresql-*.txt")):
        version = path.stem.removeprefix("postgresql-")
        for line in path.read_text().splitlines():
            match = CODE_LINE.match(line)
            if match is None:
                continue
            code, severity, _macro, name = match.groups()
            # A line with no condition name is a second macro for a code that
            # an earlier line already named.
            if name is None:
                continue
            entry = codes.setdefault(code, (severity, name, []))
            if entry[1] != name:
                raise SystemExit(f"{code} has two names: {entry[1]} and {name}")
            entry[2].append(version)
    return codes


def read_classes():
    """Every class of every input file: two characters -> PascalCase title."""
    classes = {}
    for path in sorted(INPUT_DIRECTORY.glob("postgresql-*.txt")):
        for line in path.read_text().splitlines():
            match = CLASS_LINE.match(line)
            if match is None:
                continue
            class_code, title = match.groups()
            words = re.findall(r"[A-Za-z0-9]+", title)
            name = "".join(word.capitalize() for word in words) + "Class"
            if classes.setdefault(class_code, name) != name:
                raise SystemExit(f"class {class_code} has two titles")
    return classes


def pascal_case(name):
    return "".join(part.capitalize() for part in name.split("_"))


def variant_names(codes):
    """The Gleam variant name of each code."""
    by_name = {}
    for code, (_severity, name, _versions) in codes.items():
        by_name.setdefault(name, []).append(code)
    class_names = {code[:2]: name for code, (_s, name, _v) in codes.items() if code.endswith("000")}
    variants = {}
    for code, (_severity, name, _versions) in codes.items():
        if len(by_name[name]) == 1:
            variants[code] = pascal_case(name)
        else:
            variants[code] = pascal_case(class_names[code[:2]]) + pascal_case(name)
    if len(set(variants.values())) != len(variants):
        raise SystemExit("two codes have the same variant name")
    return variants


def versions_text(versions, all_versions):
    if versions == all_versions:
        return ""
    return " Only in PostgreSQL " + ", ".join(versions) + "."


def render(codes, variants, classes):
    all_versions = sorted({v for (_s, _n, versions) in codes.values() for v in versions})
    ordered = sorted(codes)
    lines = [
        "//// The SQLSTATE codes of PostgreSQL " + ", ".join(all_versions) + ", one variant each.",
        "////",
        "//// Generated by scripts/generate_sql_state.py from test/fixtures/errcodes.",
        "//// Do not edit this file: change the input files and run the script.",
        "",
        "import gleam/string",
        "",
        "/// A SQLSTATE code. `Unlisted` holds a code that no supported",
        "/// PostgreSQL version has, such as a code of a newer server.",
        "pub type SqlState {",
    ]
    for code in ordered:
        _severity, name, versions = codes[code]
        lines.append(f"  /// {code}, `{name}`.{versions_text(versions, all_versions)}")
        lines.append(f"  {variants[code]}")
    lines += [
        "  /// A code that no supported PostgreSQL version has.",
        "  Unlisted(code: String)",
        "}",
        "",
        "/// The SQLSTATE of a five-character code. A code that no supported",
        "/// version has gives `Unlisted`, so a newer server never fails here.",
        "pub fn parse_sql_state(code: String) -> SqlState {",
        "  case code {",
    ]
    for code in ordered:
        lines.append(f'    "{code}" -> {variants[code]}')
    lines += [
        "    _ -> Unlisted(code)",
        "  }",
        "}",
        "",
        "/// The five-character code of a SQLSTATE, for example `\"23505\"`.",
        "pub fn sql_state_to_string(sql_state: SqlState) -> String {",
        "  case sql_state {",
    ]
    for code in ordered:
        lines.append(f'    {variants[code]} -> "{code}"')
    lines += [
        "    Unlisted(code) -> code",
        "  }",
        "}",
        "",
        "/// The condition name of a SQLSTATE, as PostgreSQL's documentation and",
        "/// PL/pgSQL name it, for example `\"unique_violation\"`. An `Unlisted`",
        "/// code has no name.",
        "pub fn sql_state_name(sql_state: SqlState) -> Result(String, UnlistedCode) {",
        "  case sql_state {",
    ]
    for code in ordered:
        lines.append(f'    {variants[code]} -> Ok("{codes[code][1]}")')
    lines += [
        "    Unlisted(code) -> Error(UnlistedCode(code))",
        "  }",
        "}",
        "",
        "/// A SQLSTATE that no supported PostgreSQL version names.",
        "pub type UnlistedCode {",
        "  UnlistedCode(code: String)",
        "}",
        "",
        "/// The class of a SQLSTATE: what kind of condition it is.",
        "pub type Class {",
    ]
    for class_code in sorted(classes):
        lines.append(f"  /// Class {class_code}.")
        lines.append(f"  {classes[class_code]}")
    lines += [
        "  /// A class that no supported PostgreSQL version has.",
        "  UnlistedClass(code: String)",
        "}",
        "",
        "/// The class of a SQLSTATE. Every listed code has a listed class. An",
        "/// `Unlisted` code gives the class of its first two characters.",
        "pub fn sql_state_class(sql_state: SqlState) -> Class {",
        "  case sql_state {",
    ]
    for code in ordered:
        lines.append(f"    {variants[code]} -> {classes[code[:2]]}")
    lines += [
        "    Unlisted(code) -> class_of_code(string.slice(code, at_index: 0, length: 2))",
        "  }",
        "}",
        "",
        "fn class_of_code(class_code: String) -> Class {",
        "  case class_code {",
    ]
    for class_code in sorted(classes):
        lines.append(f'    "{class_code}" -> {classes[class_code]}')
    lines += [
        "    _ -> UnlistedClass(class_code)",
        "  }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    codes = read_codes()
    variants = variant_names(codes)
    classes = read_classes()
    missing = {code[:2] for code in codes} - set(classes)
    if missing:
        raise SystemExit(f"codes with no class: {sorted(missing)}")
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(render(codes, variants, classes))
    print(f"wrote {len(codes)} codes to {OUTPUT_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
